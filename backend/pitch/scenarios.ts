export function phaseAt(startedAt: number, now = Date.now()) {
  let deadline = startedAt;
  for (let index = 0; index < PHASES.length; index++) {
    deadline += PHASES[index].seconds * 1000;
    if (now < deadline) return { ...PHASES[index], index, deadline, expired: false };
  }
  return { ...PHASES[5], index: 5, deadline, expired: true };
}
